-- Initial schema. Requires PostgreSQL 13+ (gen_random_uuid is built in).

CREATE TABLE users (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (lower(email));

-- Buy and sell orders share one table; `side` tells them apart.
-- (Previously two Supabase tables: `buy` and `tasks`.)
CREATE TYPE order_side AS ENUM ('buy', 'sell');

CREATE TABLE orders (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  side         order_side NOT NULL,
  name         TEXT       NOT NULL CHECK (length(trim(name)) > 0),
  quantity     INTEGER    NOT NULL CHECK (quantity > 0),
  unit_price   BIGINT     NOT NULL CHECK (unit_price >= 0),       -- rials per coin
  total        BIGINT     GENERATED ALWAYS AS (quantity::BIGINT * unit_price) STORED,
  jalali_date  CHAR(10)   NOT NULL CHECK (jalali_date ~ '^[0-9]{4}/[0-9]{2}/[0-9]{2}$'),
  delivery     TEXT,
  description  TEXT,
  status       TEXT       NOT NULL DEFAULT 'تسویه نشده'
               CHECK (status IN ('تسویه نشده', 'پرداخت شده', 'تحویل شده')),
  accounting   BOOLEAN    NOT NULL DEFAULT false,
  created_by   UUID REFERENCES users (id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX orders_side_created_idx ON orders (side, created_at DESC, id DESC);
CREATE INDEX orders_side_date_idx    ON orders (side, jalali_date);

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER orders_set_updated_at
  BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
