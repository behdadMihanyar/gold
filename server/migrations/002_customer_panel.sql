-- Connection state of the price feed (one row). `last_heartbeat_at` stays NULL
-- until a collector reports in, which means "manual prices" mode.
CREATE TABLE price_feed (
  id                BOOLEAN PRIMARY KEY DEFAULT true CHECK (id),
  connected         BOOLEAN     NOT NULL DEFAULT false,
  last_heartbeat_at TIMESTAMPTZ,
  last_price_at     TIMESTAMPTZ
);
INSERT INTO price_feed DEFAULT VALUES;

-- Latest values received per feed item, including items not yet mapped to a
-- product, so an admin can match them to products by looking at the prices.
CREATE TABLE price_feed_items (
  source_id  INTEGER PRIMARY KEY,
  buy_price  BIGINT,
  sell_price BIGINT,
  seen_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- buy / sell requests

CREATE TYPE request_status AS ENUM ('pending', 'accepted', 'rejected', 'cancelled');

CREATE TABLE trade_requests (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         UUID           NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  product_id      SMALLINT       NOT NULL REFERENCES products (id),
  product_name    TEXT           NOT NULL,                        -- snapshot at request time
  unit            TEXT           NOT NULL,
  side            order_side     NOT NULL,                        -- customer's point of view
  quantity        NUMERIC(12,3)  NOT NULL CHECK (quantity > 0),
  unit_price      BIGINT         NOT NULL CHECK (unit_price > 0), -- locked when the request is sent
  total           BIGINT         GENERATED ALWAYS AS (round(quantity * unit_price)::bigint) STORED,
  status          request_status NOT NULL DEFAULT 'pending',
  customer_note   TEXT,
  admin_note      TEXT,
  client_key      UUID,                                           -- makes double-submits / retries harmless
  created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
  decided_at      TIMESTAMPTZ,
  decided_by      UUID REFERENCES users (id) ON DELETE SET NULL,
  seen_at         TIMESTAMPTZ,                                    -- when the customer saw the decision
  ledger_order_id BIGINT REFERENCES orders (id) ON DELETE SET NULL,
  CHECK ((status = 'pending') = (decided_at IS NULL))
);

CREATE UNIQUE INDEX trade_requests_client_key_idx
  ON trade_requests (user_id, client_key) WHERE client_key IS NOT NULL;
CREATE INDEX trade_requests_user_idx    ON trade_requests (user_id, created_at DESC, id DESC);
CREATE INDEX trade_requests_status_idx  ON trade_requests (status, created_at DESC, id DESC);
CREATE INDEX trade_requests_unseen_idx  ON trade_requests (user_id, decided_at DESC)
  WHERE seen_at IS NULL AND status IN ('accepted', 'rejected');
