-- Customer panel: roles, customer accounts, the price board and buy/sell requests.
--
-- Terminology
--   * An `orders` row (the admin ledger) is written from the SHOP's point of view:
--     side 'sell' = the shop sold coins to someone.
--   * A `trade_requests` row is written from the CUSTOMER's point of view:
--     side 'buy' = the customer wants to buy from the shop (the shop sells).
--   * products.buy_price  = what a customer PAYS to buy from the shop (higher, green).
--     products.sell_price = what a customer RECEIVES when selling to the shop (lower, red).
--     NULL means "not available" (shown as «ندارید»).

-- ---------------------------------------------------------------- roles & customers

CREATE TYPE user_role AS ENUM ('admin', 'customer');

ALTER TABLE users
  ADD COLUMN role      user_role NOT NULL DEFAULT 'customer',
  ADD COLUMN username  TEXT,
  ADD COLUMN full_name TEXT,
  ADD COLUMN phone     TEXT,
  ADD COLUMN is_active BOOLEAN NOT NULL DEFAULT true;

-- Every account that exists before the customer panel is a dashboard (admin) user.
UPDATE users SET role = 'admin';

-- Customers sign in with a username chosen by the admin; admins keep their email.
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;

ALTER TABLE users
  ADD CONSTRAINT users_login_chk
    CHECK (email IS NOT NULL OR username IS NOT NULL),
  ADD CONSTRAINT users_admin_email_chk
    CHECK (role <> 'admin' OR email IS NOT NULL),
  ADD CONSTRAINT users_username_format_chk
    CHECK (username IS NULL OR username ~ '^[a-z0-9._-]{3,32}$');

CREATE UNIQUE INDEX users_username_key ON users (username);

-- ---------------------------------------------------------------- products & price board

CREATE TABLE products (
  id                SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              TEXT          NOT NULL UNIQUE,
  name              TEXT          NOT NULL,
  group_name        TEXT          NOT NULL,
  group_order       SMALLINT      NOT NULL,
  sort_order        SMALLINT      NOT NULL,
  unit              TEXT          NOT NULL,                       -- عدد / مثقال / گرم
  min_quantity      NUMERIC(12,3) NOT NULL DEFAULT 1   CHECK (min_quantity > 0),
  max_quantity      NUMERIC(12,3) NOT NULL DEFAULT 1000,
  quantity_step     NUMERIC(12,3) NOT NULL DEFAULT 1   CHECK (quantity_step > 0),
  buy_price         BIGINT CHECK (buy_price  IS NULL OR buy_price  > 0),
  sell_price        BIGINT CHECK (sell_price IS NULL OR sell_price > 0),
  source_id         INTEGER UNIQUE,                               -- item id in the price feed (collector)
  is_active         BOOLEAN       NOT NULL DEFAULT true,
  ledger_sync       BOOLEAN       NOT NULL DEFAULT false,         -- may be mirrored into `orders` (whole coins only)
  prices_updated_at TIMESTAMPTZ,
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CHECK (max_quantity >= min_quantity)
);

CREATE TRIGGER products_set_updated_at
  BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

