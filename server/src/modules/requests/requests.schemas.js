import { z } from "zod";
import { parseQuantity } from "../../utils/numbers.js";
import { normalizePrice } from "../prices/prices.schemas.js";

export const STATUSES = ["pending", "accepted", "rejected", "cancelled"];

const quantity = z
  .union([z.number(), z.string()])
  .transform(parseQuantity)
  .pipe(
    z
      .number({ invalid_type_error: "Quantity must be a number" })
      .finite("Quantity must be a number")
      .positive("Quantity must be greater than zero"),
  );

const note = z
  .string()
  .trim()
  .max(300)
  .nullish()
  .transform((v) => (v ? v : null));

export const createRequestBody = z.object({
  productId: z.coerce.number().int().positive(),
  side: z.enum(["buy", "sell"]),
  quantity,
  // The price the customer saw. If the market moved meanwhile the server answers
  // PRICE_CHANGED instead of silently using a different price.
  quotedPrice: z
    .union([z.number(), z.string(), z.null()])
    .optional()
    .transform(normalizePrice),
  note,
  // Generated by the browser per attempt; makes a double click or a retry harmless.
  clientKey: z.string().uuid().optional(),
});

const page = {
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
};

export const customerListQuery = z.object({
  status: z.enum([...STATUSES, "all"]).default("all"),
  ...page,
});

export const adminListQuery = z.object({
  status: z.enum([...STATUSES, "all"]).default("all"),
  side: z.enum(["buy", "sell"]).optional(),
  userId: z.string().uuid().optional(),
  q: z.preprocess((v) => (v === "" ? undefined : v), z.string().trim().max(100).optional()),
  ...page,
});

export const idParams = z.object({ id: z.coerce.number().int().positive() });

export const seenBody = z.object({
  ids: z.array(z.number().int().positive()).max(200).optional(),
});

export const acceptBody = z.object({
  note,
  // Also write the deal into the admin ledger (`orders`). Only coins in whole numbers qualify.
  recordInLedger: z.boolean().default(false),
});

export const rejectBody = z.object({ note });
